CREATE TABLE IF NOT EXISTS live_market_cache (
 cache_key TEXT PRIMARY KEY,
 payload TEXT,
 fetched INTEGER NOT NULL DEFAULT 0,
 lease INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS live_market_guard (
 id INTEGER PRIMARY KEY CHECK(id = 1),
 fingerprint TEXT NOT NULL,
 day TEXT NOT NULL DEFAULT '',
 daily_calls INTEGER NOT NULL DEFAULT 0,
 minute INTEGER NOT NULL DEFAULT 0,
 minute_calls INTEGER NOT NULL DEFAULT 0,
 next_call INTEGER NOT NULL DEFAULT 0,
 paused_until INTEGER NOT NULL DEFAULT 0,
 failures INTEGER NOT NULL DEFAULT 0,
 status TEXT NOT NULL DEFAULT 'ok'
);
